import { expect, test } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import type { Experiment, Study } from '../src/types'

test('real complete workflow: configure, train two MLPs, compare, select, evaluate and export', async ({ page }) => {
  test.setTimeout(120000)
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByLabel('Treino (%)')).toBeEnabled()
  await page.getByLabel('Treino (%)').fill('60')
  await expect(page.getByRole('button', { name: 'Aplicar percentuais' })).toBeDisabled()
  await page.getByLabel('Validação (%)').fill('20')
  await page.getByLabel('Teste (%)').fill('20')
  await page.getByRole('button', { name: 'Aplicar percentuais' }).click()
  await expect(page.locator('.split-counts')).toContainText('6.000')
  await page.reload()
  await expect(page.getByLabel('Treino (%)')).toHaveValue('60')
  await page.getByRole('navigation').getByRole('button', { name: /Construa a MLP/ }).click()
  await expect(page.getByRole('region', { name: 'Resumo da arquitetura' })).toBeVisible()
  const originalCount = await page.locator('.parameter-total').innerText()
  await page.getByLabel('Neurônios da camada 1', { exact: true }).fill('8')
  await expect(page.locator('.parameter-total')).not.toHaveText(originalCount)
  await page.getByRole('button', { name: 'Remover camada 2' }).click()
  await page.getByLabel('Nome do experimento').fill('MLP real A')
  await page.getByRole('button', { name: 'Configurar treinamento', exact: true }).click()
  await page.getByLabel('Épocas solicitadas').fill('2')
  await page.getByLabel('Batch size', { exact: true }).fill('128')
  const createdPromise = page.waitForResponse((response) => response.url().endsWith('/api/experiments') && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'Treinar novo experimento', exact: true }).click()
  const first: Experiment = await (await createdPromise).json()
  expect(first.status).toBe('queued')
  await expect(page.locator('.run-results .status-completed')).toBeVisible({ timeout: 60000 })
  await expect(page.getByRole('link', { name: 'Relatório parcial HTML', exact: true })).toBeVisible()
  await expect(page.getByText(/Relatório parcial: a tabela de Precision/)).toBeVisible()
  const partialResponse = await page.request.get(`/api/experiments/${first.id}/export?format=html`)
  const partialReport = await page.context().newPage()
  await partialReport.setContent(await partialResponse.text())
  await expect(partialReport.getByRole('heading', { name: 'Relatório de classificação — validação', exact: true })).toBeVisible()
  await expect(partialReport.getByRole('heading', { name: 'Matriz de confusão — validação', exact: true })).toBeVisible()
  await expect(partialReport.getByRole('cell', { name: 'Média macro', exact: true })).toBeVisible()
  await expect(partialReport.getByRole('cell', { name: 'Média ponderada', exact: true })).toBeVisible()
  await expect(partialReport.getByRole('table')).toHaveCount(2)
  await partialReport.close()
  await expect(page.getByText(/O rascunho mudou/)).toHaveCount(0)
  await expect(page.getByRole('img', { name: /Curvas reais de acurácia/ })).toBeVisible()
  await expect(page.getByRole('img', { name: /Curvas reais de perda/ })).toBeVisible()
  expect(first.config.preprocess.train_percent).toBe(60)
  await expect(page.getByRole('region', { name: 'Métricas de validação do modelo salvo' })).toBeVisible()
  await page.screenshot({ path: 'test-results/treinamento-real.png', fullPage: true })
  await page.getByRole('navigation').getByRole('button', { name: /Construa a MLP/ }).click()
  await page.getByLabel('Nome do experimento').fill('MLP real B')
  await page.getByLabel('Neurônios da camada 1', { exact: true }).fill('12')
  await expect(page.getByText(/O rascunho mudou/)).toBeVisible()
  await page.getByRole('button', { name: 'Configurar treinamento', exact: true }).click()
  const secondPromise = page.waitForResponse((response) => response.url().endsWith('/api/experiments') && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'Treinar novo experimento', exact: true }).click()
  const second: Experiment = await (await secondPromise).json()
  expect(second.id).not.toBe(first.id)
  await expect(page.locator('.run-results .status-completed')).toBeVisible({ timeout: 60000 })
  await page.getByRole('button', { name: 'Validar e comparar', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Tabela de experimentos' })).toBeVisible()
  await page.getByLabel('Comparar MLP real A', { exact: true }).check()
  await page.getByLabel('Comparar MLP real B', { exact: true }).check()
  await expect(page.getByRole('img', { name: /Curvas reais de perda de 2 experimento/ })).toBeVisible()
  await page.screenshot({ path: 'test-results/comparacao-real.png', fullPage: true })
  const rows = page.getByRole('region', { name: 'Tabela de experimentos' }).locator('tbody tr')
  await rows.first().getByRole('button', { name: 'Selecionar para teste', exact: true }).click()
  await expect(page).toHaveURL(/#etapa-9$/)
  await expect(page.getByRole('button', { name: 'Avaliar no teste final', exact: true })).toBeDisabled()
  await page.getByLabel(/Confirmo que escolhi este experimento/).check()
  const finalPromise = page.waitForResponse((response) => response.url().endsWith('/api/evaluation/final') && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'Avaliar no teste final', exact: true }).click()
  const final: Study = await (await finalPromise).json()
  expect(final.status).toBe('completed')
  expect(final.result?.samples).toBe(2000)
  expect(final.result?.confusion_matrix.flat().reduce((sum, value) => sum + value, 0)).toBe(2000)
  expect(final.result?.loss).toBeGreaterThan(0)
  expect(final.result?.classification_report?.['0'].support).toBe(1000)
  await expect(page.getByRole('heading', { name: 'Resumo do desempenho do modelo salvo' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Relatório de classificação — teste final' })).toBeVisible()
  await expect(page.getByRole('img', { name: /Curvas reais de acurácia/ })).toBeVisible()
  await expect(page.getByRole('img', { name: /Curvas reais de perda/ })).toBeVisible()
  await expect(page.getByRole('table', { name: /Linhas: classe real/ })).toBeVisible()
  await expect(page.getByRole('region', { name: 'Métricas finais do teste' })).toBeVisible()
  await page.getByText('Ver o Python', { exact: true }).click()
  await expect(page.locator('pre')).toContainText('result["confusion_matrix"]')
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('link', { name: 'Relatório final HTML', exact: true }).click()
  expect((await downloadPromise).suggestedFilename()).toMatch(/ann-lab-.*\.html$/)
  const exported = await page.request.get(`/api/experiments/${final.selected_experiment_id}/export?format=html`)
  const report = await page.context().newPage()
  await report.setContent(await exported.text())
  await expect(report.getByRole('img', { name: 'Acurácia × Épocas', exact: true })).toBeVisible()
  await expect(report.getByRole('img', { name: 'Loss × Épocas', exact: true })).toBeVisible()
  await expect(report.getByRole('columnheader', { name: 'Categoria / Métrica', exact: true })).toBeVisible()
  await expect(report.getByRole('cell', { name: 'Média macro', exact: true })).toBeVisible()
  await expect(report.getByRole('cell', { name: 'Média ponderada', exact: true })).toBeVisible()
  await expect(report.getByRole('cell', { name: 'Acurácia', exact: true })).toBeVisible()
  await expect(report.getByRole('heading', { level: 2 })).toHaveCount(4)
  await expect(report.getByRole('table')).toHaveCount(2)
  await expect(report.getByRole('heading', { level: 1 })).toHaveCount(0)
  expect(await report.locator('th, td').evaluateAll((cells) => cells.every((cell) => getComputedStyle(cell).backgroundColor === 'rgb(255, 255, 255)'))).toBe(true)
  expect(await report.locator('h2, th').evaluateAll((titles) => titles.every((title) => getComputedStyle(title).color === 'rgb(0, 0, 0)'))).toBe(true)
  await report.screenshot({ path: 'test-results/relatorio-html.png', fullPage: true })
  await report.close()
  await page.reload()
  await expect(page.getByRole('table', { name: /Linhas: classe real/ })).toBeVisible()
  await page.screenshot({ path: 'test-results/avaliacao-real.png', fullPage: true })
  expect(errors).toEqual([])
})

test('learning pages pass accessibility checks and mobile layout stays contained', async ({ page }) => {
  test.setTimeout(90000)
  for (const step of [6, 7, 8, 9, 10]) {
    await page.goto(step === 10 ? '/#experimentos' : `/#etapa-${step}`)
    await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
    if (step === 6) await expect(page.locator('.parameter-total')).toBeVisible()
    const result = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
    expect(result.violations.map((violation) => ({
      id: violation.id,
      nodes: violation.nodes.map((node) => ({ target: node.target, summary: node.failureSummary })),
    }))).toEqual([])
  }
  await page.setViewportSize({ width: 390, height: 844 })
  for (const step of [6, 7, 8, 9, 10]) {
    await page.goto(step === 10 ? '/#experimentos' : `/#etapa-${step}`)
    await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
    if (step === 6) await expect(page.locator('.parameter-total')).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  }
  await page.screenshot({ path: 'test-results/experimentos-mobile.png', fullPage: true })
})
